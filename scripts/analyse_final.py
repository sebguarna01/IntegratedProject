"""Every number and figure of the final study, rebuilt from the results CSVs (nothing is typed in by hand).

    python scripts/analyse_final.py            # writes results/final_tables.md and results/figures/final/*.png

Reads whatever exists under results/ and skips a block that is missing, so it can be run while the studies are still going.
Success counts a trial as docked only if it finished inside the common cap (CAP, 300 s). Intervals: Wilson for proportions,
bootstrap over seeds for paired differences of continuous metrics, exact McNemar for paired success.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from activenav.evaluation.paired import mcnemar_exact          # noqa: E402
from activenav.evaluation.stats import bootstrap_ci, wilson_interval   # noqa: E402

CAP = 300.0
RES = ROOT / "results"
COLORS = {"B": "#2a78d6", "C-sweep": "#eb6a34", "C-info": "#1bb07a"}


def load(folder: str, subdir: str | None = None) -> list[dict]:
    """All camera study rows under results/<folder> (one level of files), with docked recomputed against the cap."""
    rows = []
    for p in sorted((RES / folder).glob("search_study_camera*.csv")):
        for r in csv.DictReader(open(p, newline="")):
            r["folder"] = folder
            r["seed"] = int(r["seed"])
            r["z"] = float(r["dock_height_m"]) if r.get("dock_height_m") not in (None, "", "nan") else float("nan")
            r["ok"] = r["docked"] == "1" and float(r["duration_s"]) <= CAP
            rows.append(r)
    return rows


def num(r, k):
    try:
        return float(r.get(k, "nan") or "nan")
    except ValueError:
        return float("nan")


def frac(rows) -> str:
    n = len(rows)
    if n == 0:
        return "-"
    k = sum(r["ok"] for r in rows)
    lo, hi = wilson_interval(k, n)
    return f"{k}/{n} ({100 * k / n:.0f}%)"


def cell_ci(rows) -> tuple[float, float, float]:
    n = len(rows)
    k = sum(r["ok"] for r in rows)
    lo, hi = wilson_interval(k, n)
    return 100 * k / n, 100 * lo, 100 * hi


def paired(a_rows, b_rows, key):
    """Pair rows of two sets by (level, layout, seed); returns dicts of the two rows."""
    ix = {(r["level"], r["layout"], r["seed"]): r for r in b_rows}
    return [(r, ix[(r["level"], r["layout"], r["seed"])]) for r in a_rows if (r["level"], r["layout"], r["seed"]) in ix]


def md_table(head, body):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(out)


def main():
    out = ["# Final study tables (generated by scripts/analyse_final.py)\n", f"Common cap {CAP:.0f} s. Rows counted as docked only inside the cap.\n"]
    figdir = RES / "figures" / "final"
    figdir.mkdir(parents=True, exist_ok=True)
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    main_rows = load(".")
    height = load("height") + load("heldout")
    height = [r for r in height if r["layout"].startswith("fixed+dock")]
    dock02 = load("dock02")
    adaptive = load("adaptive") if (RES / "adaptive").exists() else []
    tilt_free = load("tilt_free") if (RES / "tilt_free").exists() else []
    lqr = load("lqr") if (RES / "lqr").exists() else []

    # ---------------------------------------------------------------- 1. dock height
    series = {"B": [r for r in height if r["config"] == "B"], "C-sweep": [r for r in height if r["config"] == "C-sweep"],
              "C-info": [r for r in height if r["config"] == "C-info"]}
    if tilt_free:
        series["B, tilt free"] = tilt_free
    if adaptive:
        series["B + dock-tilt rule"] = [r for r in adaptive if r["config"] == "B"]
        series["C-sweep + dock-tilt rule"] = [r for r in adaptive if r["config"] == "C-sweep"]
    heights = sorted({r["z"] for r in height})
    body = []
    for z in heights:
        row = [f"{z:g} m"]
        for name, rs in series.items():
            sub = [r for r in rs if abs(r["z"] - z) < 1e-6]
            row.append(frac(sub))
        body.append(row)
    out += ["## 1. Docking success by dock-marker height (development seeds 0..19 and held-out seeds 5000..5019 pooled)\n",
            md_table(["height"] + list(series), body), ""]
    fig, ax = plt.subplots(figsize=(7.5, 4.2))
    styles = {"B": ("o", "-"), "C-sweep": ("s", "-"), "C-info": ("^", "-"), "B, tilt free": ("o", ":"),
              "B + dock-tilt rule": ("o", "--"), "C-sweep + dock-tilt rule": ("s", "--")}
    for name, rs in series.items():
        xs, ys, lo, hi = [], [], [], []
        for z in heights:
            sub = [r for r in rs if abs(r["z"] - z) < 1e-6]
            if sub:
                p, l, h = cell_ci(sub)
                xs.append(z); ys.append(p); lo.append(p - l); hi.append(h - p)
        base = name.split(",")[0].split(" +")[0]
        mk, ls = styles.get(name, ("o", "-"))
        ax.errorbar(xs, ys, yerr=[lo, hi], marker=mk, ls=ls, color=COLORS.get(base, "#777"), label=name, capsize=3, lw=1.6)
    ax.set_xlabel("dock marker centre height [m]"); ax.set_ylabel("docked [%]"); ax.set_ylim(-5, 105)
    ax.set_xticks(heights); ax.legend(fontsize=8, frameon=False); ax.grid(alpha=0.25)
    ax.set_title("Docking success against dock height (Wilson 95%)", fontsize=10, loc="left")
    fig.tight_layout(); fig.savefig(figdir / "height_cliff.png", dpi=150); plt.close(fig)

    # ---------------------------------------------------------------- 2. false docks
    allrows = main_rows + height + dock02 + [r for r in load("heldout") if r["layout"] == "fixed"]
    fd = [r for r in allrows if r["outcome"] == "false dock"]
    body = []
    for z in sorted({r["z"] for r in allrows}):
        row = [f"{z:g} m"]
        for c in ["B", "C-sweep", "C-info"]:
            sub = [r for r in allrows if abs(r["z"] - z) < 1e-6 and r["config"] == c]
            row.append(f"{sum(r['outcome'] == 'false dock' for r in sub)}/{len(sub)}")
        body.append(row)
    out += ["## 2. False docks (the robot stops and claims the dock, but misses the 0.10 m / 5 deg tolerance), by dock height\n",
            md_table(["height", "B", "C-sweep", "C-info"], body),
            f"\nMedian yaw error of a false dock: {np.median([num(r, 'yaw_err_deg') for r in fd]):.1f} deg (n = {len(fd)}).\n"]
    if dock02:
        body = [[c, frac([r for r in dock02 if r["config"] == c])] for c in ["B", "C-sweep", "C-info"]]
        out += ["Fresh seeds (6000..6039) at 0.2 m:\n", md_table(["config", "docked"], body), ""]

    # ---------------------------------------------------------------- 3. main block: estimation by room
    rooms = sorted({r["level"] for r in main_rows})
    body = []
    fig, ax = plt.subplots(figsize=(9, 4.2))
    for ci, c in enumerate(["B", "C-sweep", "C-info"]):
        meds = []
        for ri, lv in enumerate(rooms):
            v = [num(r, "pos_rmse_m") * 1000 for r in main_rows if r["level"] == lv and r["config"] == c]
            meds.append(np.nanmedian(v))
            ax.scatter(np.full(len(v), ri + (ci - 1) * 0.25) + np.linspace(-0.07, 0.07, len(v)), v, s=6, color=COLORS[c], alpha=0.35)
        ax.plot(np.arange(len(rooms)) + (ci - 1) * 0.25, meds, "_", ms=14, mew=2.5, color=COLORS[c], label=c)
    ax.set_xticks(range(len(rooms))); ax.set_xticklabels(rooms, rotation=30, ha="right", fontsize=8)
    ax.set_yscale("log"); ax.set_ylabel("position RMSE [mm] (one dot per seed, bar = median)"); ax.legend(frameon=False, fontsize=8)
    ax.set_title("State estimation error by room", fontsize=10, loc="left"); ax.grid(alpha=0.25, axis="y")
    fig.tight_layout(); fig.savefig(figdir / "estimation_by_room.png", dpi=150); plt.close(fig)
    for lv in rooms + ["ALL"]:
        row = [lv]
        for c in ["B", "C-sweep", "C-info"]:
            sub = [r for r in main_rows if (lv == "ALL" or r["level"] == lv) and r["config"] == c]
            row.append(f"{frac(sub)}; {np.nanmedian([num(r, 'pos_rmse_m') for r in sub]) * 1000:.1f} mm; NEES {np.nanmedian([num(r, 'nees_consistent') for r in sub]):.2f}")
        body.append(row)
    out += ["## 3. Main block, 12 rooms: docked; median position RMSE; median share of time inside the NEES 95% band\n",
            md_table(["room", "B", "C-sweep", "C-info"], body), ""]
    body = []
    for a, b in [("C-info", "B"), ("C-sweep", "B"), ("C-info", "C-sweep")]:
        A = [r for r in main_rows if r["config"] == a]; B = [r for r in main_rows if r["config"] == b]
        pr = paired(A, B, None)
        d = np.array([num(x, "pos_rmse_m") - num(y, "pos_rmse_m") for x, y in pr]) * 1000
        lo, hi = bootstrap_ci(d)[1:] if len(bootstrap_ci(d)) == 3 else bootstrap_ci(d)
        w = sum(x["ok"] and not y["ok"] for x, y in pr); l = sum(y["ok"] and not x["ok"] for x, y in pr)
        body.append([f"{a} - {b}", len(pr), f"{np.nanmedian(d):+.1f} mm [{lo:+.1f}, {hi:+.1f}]", f"{w}W {l}L", f"{mcnemar_exact(w, l):.2f}"])
    out += ["Paired over all rooms (same seed and room): position RMSE difference (negative = first config better), docking wins/losses.\n",
            md_table(["pair", "pairs", "RMSE diff, median [95% CI]", "docking", "McNemar p"], body), ""]

    # ---------------------------------------------------------------- 4. LQR vs go_to_point
    if lqr:
        gtp = main_rows + load("height") + load("heldout")
        body = []
        for lv_label, sel in [("large_6_pillars", lambda r: r["level"] == "large_6_pillars" and r["layout"] == "fixed" and r["seed"] < 1000),
                              ("cluttered_14", lambda r: r["level"] == "cluttered_14" and r["layout"] == "fixed" and r["seed"] < 1000),
                              ("height study", lambda r: r["layout"].startswith("fixed+dock") and r["seed"] < 1000)]:
            for c in ["B", "C-sweep", "C-info"]:
                A = [r for r in gtp if r["config"] == c and sel(r)]
                B = [r for r in lqr if r["config"] == c and sel(r)]
                pr = paired(A, B, None)
                if not pr:
                    continue
                w = sum(x["ok"] and not y["ok"] for x, y in pr); l = sum(y["ok"] and not x["ok"] for x, y in pr)
                body.append([lv_label, c, len(pr), sum(x["ok"] for x, _ in pr), sum(y["ok"] for _, y in pr), f"{w}/{l}", f"{mcnemar_exact(w, l):.2f}"])
        out += ["## 4. LQR follower against go_to_point, same seeds\n",
                md_table(["scope", "config", "pairs", "go_to_point docked", "LQR docked", "gtp-only / LQR-only", "McNemar p"], body), ""]

    # ---------------------------------------------------------------- 5. sensitivity
    sens = [("baseline", main_rows, lambda r: r["level"] == "large_6_pillars")]
    for v in ["Q05", "Q2", "R05", "R2"]:
        if (RES / f"sens_{v}").exists():
            sens.append((v, load(f"sens_{v}"), lambda r: True))
    body = []
    for name, rows, sel in sens:
        row = [name]
        for c in ["B", "C-info"]:
            sub = [r for r in rows if r["config"] == c and sel(r)]
            row.append(f"{frac(sub)}; {np.nanmedian([num(r, 'pos_rmse_m') for r in sub]) * 1000:.1f} mm; NEES {np.nanmedian([num(r, 'nees_consistent') for r in sub]):.2f}; sigma {np.nanmedian([num(r, 'sigma_xy_mean_m') for r in sub]) * 1000:.1f} mm")
        body.append(row)
    out += ["## 5. Estimator sensitivity (Q and R scaled by 0.5 and 2), large_6_pillars\n", md_table(["run", "B", "C-info"], body), ""]

    # ---------------------------------------------------------------- 6. other rooms
    hr = load("height_rooms") if (RES / "height_rooms").exists() else []
    if hr:
        body = []
        for lv in sorted({r["level"] for r in hr}):
            for z in sorted({r["z"] for r in hr}):
                body.append([lv, f"{z:g} m"] + [frac([r for r in hr if r["level"] == lv and abs(r["z"] - z) < 1e-6 and r["config"] == c]) for c in ["B", "C-sweep", "C-info"]])
        out += ["## 6. Dock height in other rooms (seeds 5000..)\n", md_table(["room", "height", "B", "C-sweep", "C-info"], body), ""]

    # ---------------------------------------------------------------- 7. gaze behaviour
    gz = load("gaze") if (RES / "gaze").exists() else []
    if gz:
        keys = [("gaze_switch_per_min", "pan reversals / min"), ("gaze_dwell_med_s", "median still-gaze time [s]"),
                ("gaze_toward_travel", "share looking where it is going"), ("gaze_lead_s", "gaze lead [s] (exploratory)"),
                ("pan_std_rad", "pan spread [rad]"), ("head_tilt_travel_rad", "tilt travel [rad]")]
        body = []
        for lv in sorted({r["level"] for r in gz}) + ["ALL"]:
            for k, label in keys:
                row = [lv, label]
                for c in ["B", "C-sweep", "C-info"]:
                    v = [num(r, k) for r in gz if (lv == "ALL" or r["level"] == lv) and r["config"] == c]
                    q = np.nanpercentile(v, [25, 50, 75]) if np.isfinite(v).any() else [np.nan] * 3
                    row.append(f"{q[1]:.2f} [{q[0]:.2f}, {q[2]:.2f}]")
                body.append(row)
        out += ["## 7. Gaze behaviour: median [IQR] per config (cues that could read as purposeful looking; descriptive, not a perception result)\n",
                md_table(["room", "metric", "B", "C-sweep", "C-info"], body), ""]
        fig, axs = plt.subplots(1, 3, figsize=(10, 3.4))
        for ax, (k, label) in zip(axs, [keys[0], keys[2], keys[4]]):
            for ci, c in enumerate(["B", "C-sweep", "C-info"]):
                v = np.array([num(r, k) for r in gz if r["config"] == c]); v = v[np.isfinite(v)]
                ax.boxplot(v, positions=[ci], widths=0.5, patch_artist=True, boxprops=dict(facecolor=COLORS[c], alpha=0.5), medianprops=dict(color="k"))
            ax.set_xticks(range(3)); ax.set_xticklabels(["B", "C-sweep", "C-info"]); ax.set_title(label, fontsize=9, loc="left"); ax.grid(alpha=0.25, axis="y")
        fig.tight_layout(); fig.savefig(figdir / "gaze_behaviour.png", dpi=150); plt.close(fig)

    (RES / "final_tables.md").write_text("\n".join(out))
    print("\n".join(out))
    print(f"\nwrote {RES / 'final_tables.md'} and figures in {figdir}")


if __name__ == "__main__":
    main()
